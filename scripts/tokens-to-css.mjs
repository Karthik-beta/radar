#!/usr/bin/env node
// Renders design/tokens.json into crates/web/style/tokens.css, a Tailwind v4 @theme block.
// Usage: node scripts/tokens-to-css.mjs [--check] [--tokens <file>] [--out <file>]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { collect, format } from './lib/tokens.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const namespaces = [
  [['color'], 'color'],
  [['font', 'family'], 'font'],
  [['font', 'weight'], 'font-weight'],
  [['font', 'size'], 'text'],
  [['space'], 'spacing'],
  [['radius'], 'radius'],
  [['motion', 'duration'], 'duration'],
  [['motion', 'easing'], 'ease'],
  [['breakpoint'], 'breakpoint'],
];

function propertyName(token) {
  for (const [prefix, namespace] of namespaces) {
    if (prefix.every((part, i) => token.path[i] === part)) {
      return `--${namespace}-${token.path.slice(prefix.length).join('-')}`;
    }
  }
  throw new Error(`no Tailwind namespace for ${token.path.join('.')}`);
}

export function render(tree) {
  const lines = collect(tree)
    .map((token) => [propertyName(token), format(token)])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([name, value]) => `  ${name}: ${value};`);
  return [
    '/* Generated by scripts/tokens-to-css.mjs from design/tokens.json. Generated, do not edit. */',
    '@theme {',
    '  --*: initial;',
    '',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean', default: false },
      tokens: { type: 'string', default: join(root, 'design/tokens.json') },
      out: { type: 'string', default: join(root, 'crates/web/style/tokens.css') },
    },
  });
  let css;
  try {
    css = render(JSON.parse(readFileSync(values.tokens, 'utf8')));
  } catch (err) {
    console.error(`tokens-to-css: ${err.message}`);
    process.exit(1);
  }
  if (values.check) {
    let current = null;
    try {
      current = readFileSync(values.out, 'utf8');
    } catch {}
    if (current !== css) {
      console.error(`${values.out} is stale. Run node scripts/tokens-to-css.mjs`);
      process.exit(1);
    }
    console.log(`${values.out} is current`);
  } else {
    writeFileSync(values.out, css);
    console.log(`wrote ${values.out}`);
  }
}
